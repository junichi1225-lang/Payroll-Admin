/**
 * 月額源泉徴収税額（令和8年分・甲欄・扶養親族等0人）を求める。
 *
 * @param socialInsuranceDeductedMonthly その月の「社会保険料等控除後の給与等の金額」
 *   （＝総支給 − 非課税手当 − 社会保険料の被保険者負担合計）
 * @returns 源泉徴収税額（円・整数）
 *
 * @example
 * calculateIncomeTax(300_000) // => 7,930（月額表 甲・扶養0）
 */
export function calculateIncomeTax(socialInsuranceDeductedMonthly: number): number {
  const a = Math.floor(socialInsuranceDeductedMonthly);
  if (a < MONTHLY_TABLE_MIN) return 0;
  if (a >= MONTHLY_TABLE_MAX) return calcByDenshiTokurei(a);

  // 月額表の区分検索（以上〜未満）
  for (let i = 0; i < MONTHLY_TAX_TABLE.length; i++) {
    const lower = MONTHLY_TAX_TABLE[i][0];
    const upper = i + 1 < MONTHLY_TAX_TABLE.length ? MONTHLY_TAX_TABLE[i + 1][0] : MONTHLY_TABLE_MAX;
    if (a >= lower && a < upper) return MONTHLY_TAX_TABLE[i][1];
  }
  return 0; // 到達しない
}

/**
 * 実効税率（%）を返す。
 * @param socialInsuranceDeductedMonthly その月の社会保険料等控除後の給与等の金額（円）
 */
export function calcEffectiveRate(socialInsuranceDeductedMonthly: number): number {
  if (socialInsuranceDeductedMonthly <= 0) return 0;
  return (calculateIncomeTax(socialInsuranceDeductedMonthly) / socialInsuranceDeductedMonthly) * 100;
}
