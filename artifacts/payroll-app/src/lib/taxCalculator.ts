// ───────────────────────────────────────────────────────────
// 電算機計算の特例（A ≥ 740,000円）
// （平成24年3月31日財務省告示第116号／令和7年4月30日告示第123号改正・令和8年分）
// ───────────────────────────────────────────────────────────

/**
 * 別表第一: その月の社会保険料等控除後の給与等の金額 A から給与所得控除の額を求める。
 * （1円未満の端数は切り上げ）
 */
function denshiEmploymentDeduction(a: number): number {
  let v: number;
  if (a <= 158_333) v = 54_167;
  else if (a <= 299_999) v = a * 0.30 + 6_667;
  else if (a <= 549_999) v = a * 0.20 + 36_667;
  else if (a <= 708_330) v = a * 0.10 + 91_667;
  else v = 162_500;
  return Math.ceil(v);
}

/**
 * 別表第三: 基礎控除の額（月額）。令和8年分 = 580,000円(年額) ÷ 12 = 48,333円。
 * （国税庁 denshi_01.pdf 別表第三）
 */
const DENSHI_BASIC_DEDUCTION = 48_333;

/**
 * 別表第四: 課税給与所得金額 B から税額を求める速算表。
 * 率は復興特別所得税(2.1%)込（×1.021）。税額は10円未満四捨五入。
 */
function denshiTaxFromTaxableIncome(b: number): number {
  if (b <= 0) return 0;
  let t: number;
  if (b <= 162_500) t = b * 0.05105;
  else if (b <= 275_000) t = b * 0.10210 - 8_296;
  else if (b <= 579_166) t = b * 0.20420 - 36_374;
  else if (b <= 750_000) t = b * 0.23483 - 54_113;
  else if (b <= 1_500_000) t = b * 0.33693 - 130_688;
  else if (b <= 3_333_333) t = b * 0.40840 - 237_893;
  else t = b * 0.45945 - 408_061;
  if (t < 0) t = 0;
  return Math.round(t / 10) * 10; // 10円未満四捨五入
}

/** 電算機計算の特例による月額源泉徴収税額（甲・扶養0）。 */
function calcByDenshiTokurei(a: number): number {
  const taxableIncome = Math.max(0, a - denshiEmploymentDeduction(a) - DENSHI_BASIC_DEDUCTION);
  return denshiTaxFromTaxableIncome(taxableIncome);
}

